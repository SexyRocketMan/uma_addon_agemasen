"""Collapse the generated control rig and the MMD armature into a single armature.

Self-contained on purpose: this file registers itself through the add-on's auto-loader (any
``bpy.types.Operator`` subclass under the add-on root is picked up), and the only other edit it needs is
one line in ``panels/AddonPanels.py``'s Controller panel. Delete this file and that line and the add-on
is exactly as it was.

The operator assumes the scene the MMR controller workflow leaves behind: an MMD armature whose mesh is
skinned to it, and the rigify control rig that MMR generated, which drives the MMD armature through
``MMR_复制旋转`` / ``MMR_复制位置`` / ``MMR_复制缩放`` constraints (see docs/MMR_CONTROLLER.md).

Because those constraints point at the control rig, the MMD deformation skeleton is already a *slave* of
the rig - so it can be copied into the control rig, keeping every bone name (and therefore every vertex
group, shape key driver and constraint target) intact, and the original armature deleted. The result is
one armature: rigify's controls, plus the model's own deform skeleton, wired together by the same
constraints as before, so the mesh deforms exactly as it did.

What this deliberately gives up: mmd_tools' per-bone metadata (MMD names, IK links, rigid body
information) is not carried over, and neither is the MMD armature object itself - so tools that expect a
"real" MMD skeleton (VMD export, physics) will not find one. Save the file before running.
"""
import bpy
from bpy.props import BoolProperty
from mathutils import Matrix, Vector

# prefixes rigify puts on the bones of the armature it generates; their presence identifies the control rig
CONTROL_PREFIXES = ("ORG-", "DEF-", "MCH-")
# where the copied deform skeleton is filed (hidden, so it does not clutter the viewport)
DEFORM_COLLECTION = "MMD Deform"
# constraint properties that must not be copied verbatim
SKIP_CONSTRAINT_PROPS = {"rna_type", "name", "is_valid", "error_location", "error_rotation",
                         "active", "show_expanded", "targets"}
# how close two points have to be to count as the same place
EPSILON = 1e-5


class CollapseRig(bpy.types.Operator):
    """Collapse the MMD armature into the generated control rig, so the mesh is bound to one rig"""

    bl_idname = "uma.collapse_rig"
    bl_label = "Collapse Rig"
    bl_description = ("Copy the MMD deform skeleton into the generated control rig, rebind the mesh to it "
                      "and delete the MMD armature. Run after 'Generate controller for umamusume'")
    bl_options = {'REGISTER', 'UNDO'}

    Delete_MMD_Armature: BoolProperty(
        name="Delete MMD Armature",
        description="Delete the original MMD armature once its bones have been copied into the rig. "
                    "Turn this off to keep it around (hidden) as a backup",
        default=True,
    )

    # ------------------------------------------------------------------------------------------------------------------
    # scene discovery

    @classmethod
    def poll(cls, context: bpy.types.Context):
        # pose mode is where a rigger usually is when they reach for this button, so it has to work there;
        # edit mode is not, because the operator edits bones itself
        if context.mode not in {'OBJECT', 'POSE'}:
            return False
        return any(o.type == 'ARMATURE' for o in context.scene.objects)

    @staticmethod
    def _looks_like_control_rig(obj):
        return any(bone.name.startswith(CONTROL_PREFIXES) for bone in obj.data.bones)

    @staticmethod
    def _constraint_targets(obj):
        """Every object this armature's bones point at through a constraint."""
        targets = set()
        for pose_bone in obj.pose.bones:
            for constraint in pose_bone.constraints:
                target = getattr(constraint, "target", None)
                if target is not None:
                    targets.add(target)
                for extra in getattr(constraint, "targets", ()):  # ARMATURE constraints hold a list
                    if getattr(extra, "target", None) is not None:
                        targets.add(extra.target)
        return targets

    def _find_pair(self, context):
        """Return (mmd_armature, control_rig, meshes bound to the mmd armature) or raise ValueError."""
        armatures = [o for o in context.scene.objects if o.type == 'ARMATURE']
        if len(armatures) < 2:
            raise ValueError("This scene has one armature. Collapsing needs the MMD armature and the "
                             "control rig generated by 'Generate controller for umamusume'.")

        meshes_by_armature = {}
        for obj in context.scene.objects:
            if obj.type != 'MESH':
                continue
            for modifier in obj.modifiers:
                if modifier.type == 'ARMATURE' and modifier.object is not None:
                    meshes_by_armature.setdefault(modifier.object.name, []).append(obj)

        candidates = []
        for armature in armatures:
            for target in self._constraint_targets(armature):
                if target is armature or target.type != 'ARMATURE':
                    continue
                if target.name not in {o.name for o in armatures}:
                    continue
                if not self._looks_like_control_rig(target):
                    continue
                candidates.append((armature, target))

        if not candidates:
            raise ValueError("No MMD armature driving a control rig was found. Run 'Generate controller "
                             "for umamusume' first, or pick the armature that the mesh is skinned to.")

        # prefer a pair that involves the active object or a bound mesh
        active = context.active_object
        for armature, target in candidates:
            if armature is active or target is active:
                return armature, target, meshes_by_armature.get(armature.name, [])
        for armature, target in candidates:
            if meshes_by_armature.get(armature.name):
                return armature, target, meshes_by_armature.get(armature.name, [])
        armature, target = candidates[0]
        return armature, target, meshes_by_armature.get(armature.name, [])

    # ------------------------------------------------------------------------------------------------------------------
    # helpers

    @staticmethod
    def _space_between(source, target):
        """Matrix taking a point in `source`'s armature space into `target`'s armature space."""
        return target.matrix_world.inverted() @ source.matrix_world

    @staticmethod
    def _copy_constraint(new_pose_bone, constraint, old_armature, new_armature):
        """Add a copy of `constraint` to `new_pose_bone`, with targets moved to the rig."""
        copy = new_pose_bone.constraints.new(constraint.type)
        for prop in constraint.bl_rna.properties:
            name = prop.identifier
            if name in SKIP_CONSTRAINT_PROPS or prop.is_readonly:
                continue
            try:
                setattr(copy, name, getattr(constraint, name))
            except (AttributeError, TypeError, ValueError):
                pass  # properties that only one of the two constraint types has
        copy.name = constraint.name

        for prop in ("target", "pole_target"):
            if getattr(copy, prop, None) is old_armature:
                setattr(copy, prop, new_armature)

        # ARMATURE constraints keep their targets in a sub-collection
        if constraint.type == 'ARMATURE' and hasattr(constraint, "targets"):
            try:
                while len(copy.targets) > 0:
                    copy.targets.remove(copy.targets[0])
                for extra in constraint.targets:
                    item = copy.targets.new()
                    item.target = new_armature if extra.target is old_armature else extra.target
                    item.subtarget = extra.subtarget
                    item.weight = extra.weight
            except Exception:  # noqa: BLE001 - an unreadable multi-target constraint is not worth failing over
                pass
        return copy

    @staticmethod
    def _driver_ids():
        """Everything that can own an animation data block, for the driver retarget below."""
        collections = (bpy.data.objects, bpy.data.meshes, bpy.data.materials, bpy.data.node_groups,
                       bpy.data.shape_keys, bpy.data.curves, bpy.data.armatures, bpy.data.scenes,
                       bpy.data.worlds)
        for collection in collections:
            for item in collection:
                yield item

    def _retarget_drivers(self, old_armature, new_armature):
        """Point every driver variable that reads the MMD armature at the rig instead."""
        retargeted = 0
        for item in self._driver_ids():
            animation_data = getattr(item, "animation_data", None)
            if animation_data is None:
                continue
            for driver in animation_data.drivers:
                for variable in driver.driver.variables:
                    for target in variable.targets:
                        if getattr(target, "id", None) is old_armature:
                            target.id = new_armature
                            retargeted += 1
        return retargeted

    def _move_own_drivers(self, old_armature, new_armature):
        """Drivers written on the MMD armature itself (its own pose bones) have to move to the rig."""
        moved = 0
        failed = 0
        source = old_armature.animation_data
        if source is None or not source.drivers:
            return moved, failed
        if new_armature.animation_data is None:
            new_armature.animation_data_create()
        for driver in source.drivers:
            try:
                new_driver = new_armature.animation_data.drivers.from_existing(src_driver=driver)
            except Exception:  # noqa: BLE001 - from_existing is the tidy path; fall back to a manual copy
                try:
                    new_driver = self._copy_driver_manually(driver, new_armature)
                except Exception:  # noqa: BLE001
                    failed += 1
                    continue
            for variable in new_driver.driver.variables:
                for target in variable.targets:
                    if getattr(target, "id", None) is old_armature:
                        target.id = new_armature
            moved += 1
        return moved, failed

    @staticmethod
    def _copy_driver_manually(driver, new_armature):
        new_driver = new_armature.animation_data.drivers.new(driver.data_path, index=driver.array_index)
        new_driver.driver.type = driver.driver.type
        for variable in driver.driver.variables:
            new_variable = new_driver.driver.variables.new()
            new_variable.name = variable.name
            new_variable.type = variable.type
            for source, target in zip(variable.targets, new_variable.targets):
                target.id = source.id
                target.bone_target = source.bone_target
                target.data_path = source.data_path
                target.transform_type = source.transform_type
                target.transform_space = source.transform_space
                target.rotation_mode = source.rotation_mode
                target.falloff_type = source.falloff_type
                target.use_falloff_curve = source.use_falloff_curve
        return new_driver

    @staticmethod
    def _references_to(armature):
        """Every constraint or armature modifier in the scene that still points at `armature`."""
        found = []
        for other in bpy.data.objects:
            if other is armature:
                continue
            if other.type == 'ARMATURE':
                for pose_bone in other.pose.bones:
                    for constraint in pose_bone.constraints:
                        if getattr(constraint, "target", None) is armature:
                            found.append("%s:%s" % (other.name, pose_bone.name))
                        for extra in getattr(constraint, "targets", ()):
                            if getattr(extra, "target", None) is armature:
                                found.append("%s:%s" % (other.name, pose_bone.name))
            for modifier in other.modifiers:
                if modifier.type == 'ARMATURE' and modifier.object is armature:
                    found.append("%s:modifier" % other.name)
        return found

    # ------------------------------------------------------------------------------------------------------------------
    # main

    def execute(self, context):
        try:
            mmd_armature, rig, meshes = self._find_pair(context)
        except ValueError as error:
            self.report({'ERROR'}, str(error))
            return {'CANCELLED'}

        if not meshes:
            self.report({'WARNING'}, "No mesh is skinned to %s - only the bones will be collapsed."
                                     % mmd_armature.name)

        # ---- pre-flight: refuse before touching anything ------------------------------------------------
        rig_bones = {bone.name for bone in rig.data.bones}
        clashes = sorted(bone.name for bone in mmd_armature.data.bones if bone.name in rig_bones)
        if clashes:
            self.report({'ERROR'}, "%s already has %d bone(s) with the same name as %s (%s). Nothing was "
                                   "changed." % (rig.name, len(clashes), mmd_armature.name,
                                                 ", ".join(clashes[:5])))
            return {'CANCELLED'}

        mmd_bones = list(mmd_armature.data.bones)
        space = self._space_between(mmd_armature, rig)
        rigid = space.to_3x3().normalized()
        copied = constraints = 0

        # ---- 1. copy every MMD bone into the rig, parents first ------------------------------------------
        # remember the user's context by name: the active object is usually the armature about to be deleted
        previous_active = context.view_layer.objects.active
        previous_active_name = previous_active.name if previous_active is not None else None
        previous_mode = previous_active.mode if (previous_active is not None
                                                and previous_active.type == 'ARMATURE') else 'OBJECT'
        for obj in context.selected_objects:
            obj.select_set(False)
        rig.select_set(True)
        context.view_layer.objects.active = rig
        if rig.mode != 'EDIT':
            bpy.ops.object.mode_set(mode='EDIT')

        created = []
        try:
            edit_bones = rig.data.edit_bones
            # order the bones parents-first. PMX normally stores them that way already, but the order is
            # computed rather than assumed: `placed` tracks the copies by name, because a pass that asked
            # the edit-bone list instead would never see a parent that has not been created yet
            order = []
            placed = set()
            pending = list(mmd_bones)
            while pending:
                remaining = []
                for bone in pending:
                    if bone.parent is None or bone.parent.name in placed:
                        order.append(bone)
                        placed.add(bone.name)
                    else:
                        remaining.append(bone)
                if len(remaining) == len(pending):
                    raise RuntimeError("the bone hierarchy of %s has a loop around %s"
                                       % (mmd_armature.name, remaining[0].name))
                pending = remaining

            for bone in order:
                new_bone = edit_bones.new(bone.name)
                created.append(new_bone.name)
                head = space @ bone.head_local
                tail = space @ bone.tail_local
                new_bone.head = head
                new_bone.tail = tail
                # keep the original roll: align the new bone's Z axis with the copied bone's Z axis
                new_bone.align_roll(rigid @ (bone.matrix_local.to_3x3() @ Vector((0.0, 0.0, 1.0))))
                new_bone.use_deform = bone.use_deform
                new_bone.inherit_scale = bone.inherit_scale
                new_bone.use_inherit_rotation = bone.use_inherit_rotation
                if bone.parent is not None:
                    new_bone.parent = edit_bones[bone.parent.name]
                    new_bone.use_connect = bone.use_connect and (head - new_bone.parent.tail).length < EPSILON
                copied += 1
        except Exception as error:  # noqa: BLE001 - leave the rig exactly as it was found
            for name in reversed(created):
                if name in rig.data.edit_bones:
                    rig.data.edit_bones.remove(rig.data.edit_bones[name])
            bpy.ops.object.mode_set(mode='OBJECT')
            self.report({'ERROR'}, "Could not copy the bones into %s (%s). Nothing was changed."
                                   % (rig.name, error))
            return {'CANCELLED'}
        finally:
            if rig.mode == 'EDIT':
                bpy.ops.object.mode_set(mode='OBJECT')

        # ---- 2. carry the constraints over, so the rig drives the copies exactly as it drove the original -
        for bone in mmd_bones:
            old_pose_bone = mmd_armature.pose.bones.get(bone.name)
            new_pose_bone = rig.pose.bones.get(bone.name)
            if old_pose_bone is None or new_pose_bone is None:
                continue
            for key in old_pose_bone.keys():
                if key == "_RNA_UI":
                    continue
                try:
                    new_pose_bone[key] = old_pose_bone[key]
                except (TypeError, ValueError):
                    pass  # unsupported property type; mmd_tools' own metadata is intentionally dropped
            for constraint in old_pose_bone.constraints:
                self._copy_constraint(new_pose_bone, constraint, mmd_armature, rig)
                constraints += 1

        # ---- 3. file the copies away in their own hidden collection --------------------------------------
        collection = rig.data.collections.get(DEFORM_COLLECTION)
        if collection is None:
            collection = rig.data.collections.new(DEFORM_COLLECTION)
        collection.is_visible = False
        for bone in mmd_bones:
            pose_bone = rig.pose.bones.get(bone.name)
            if pose_bone is not None:
                collection.assign(pose_bone.bone)

        # ---- 4. rebind the mesh, then delete the armature it was bound to --------------------------------
        rebound = []
        for mesh in meshes:
            world = mesh.matrix_world.copy()
            for modifier in mesh.modifiers:
                if modifier.type == 'ARMATURE' and modifier.object is mmd_armature:
                    modifier.object = rig
            if mesh.parent is mmd_armature:
                mesh.parent = rig
                mesh.parent_type = 'OBJECT'
                # keep the mesh exactly where it was: world = rig.matrix_world @ parent_inverse @ basis
                mesh.matrix_parent_inverse = rig.matrix_world.inverted() @ world
                mesh.matrix_basis = Matrix.Identity(4)
            rebound.append(mesh.name)

        # anything else parented to the armature follows the rig instead of being orphaned by the delete
        reparented = []
        for obj in list(bpy.data.objects):
            if obj.parent is mmd_armature:
                world = obj.matrix_world.copy()
                obj.parent = rig
                obj.parent_type = 'OBJECT'
                obj.matrix_parent_inverse = rig.matrix_world.inverted() @ world
                obj.matrix_basis = Matrix.Identity(4)
                reparented.append(obj.name)

        drivers = self._retarget_drivers(mmd_armature, rig)
        moved_drivers, failed_drivers = self._move_own_drivers(mmd_armature, rig)

        # ---- 5. make sure nothing still points at the armature we are about to remove --------------------
        still_referenced = self._references_to(mmd_armature)

        # every vertex group must still have a bone behind it, or the weights silently stop working
        missing_groups = {}
        for mesh in meshes:
            absent = [group.name for group in mesh.vertex_groups if group.name not in rig.data.bones]
            if absent:
                missing_groups[mesh.name] = absent

        deleted = None
        if self.Delete_MMD_Armature and not still_referenced:
            data = mmd_armature.data
            deleted = mmd_armature.name
            bpy.data.objects.remove(mmd_armature, do_unlink=True)
            if data.users == 0:
                bpy.data.armatures.remove(data)

        # put the user back where they were
        for obj in context.selected_objects:
            obj.select_set(False)
        target = bpy.data.objects.get(previous_active_name) if previous_active_name else None
        target = target if target is not None else rig
        target.select_set(True)
        context.view_layer.objects.active = target
        # pose mode is worth restoring (that is where the user works); edit mode is not, since the rig's
        # bones were just rewritten
        if target.type == 'ARMATURE' and previous_mode == 'POSE' and target.mode != 'POSE':
            try:
                bpy.ops.object.mode_set(mode='POSE')
            except RuntimeError:
                pass

        # ---- report -------------------------------------------------------------------------------------
        parts = ["copied %d bones and %d constraints into %s" % (copied, constraints, rig.name)]
        if rebound:
            parts.append("rebound %s" % ", ".join(rebound))
        if reparented:
            parts.append("re-parented %s" % ", ".join(reparented))
        parts.append("retargeted %d driver variable(s)" % drivers)
        if moved_drivers:
            parts.append("moved %d driver(s) off the MMD armature" % moved_drivers)
        parts.append("deleted %s" % deleted if deleted else "kept the MMD armature")
        message = "; ".join(parts)

        problems = []
        if still_referenced:
            problems.append("%d constraint/modifier target(s) still point at %s (%s), so it was kept"
                            % (len(still_referenced), mmd_armature.name, ", ".join(still_referenced[:4])))
        if missing_groups:
            problems.append("vertex groups without a bone: %s"
                            % ", ".join("%s(%d)" % (name, len(groups))
                                        for name, groups in missing_groups.items()))
        if failed_drivers:
            problems.append("%d driver(s) could not be moved" % failed_drivers)
        if problems:
            self.report({'WARNING'}, message + ". " + ". ".join(problems))
        else:
            self.report({'INFO'}, message)
        return {'FINISHED'}
